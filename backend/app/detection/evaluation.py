"""Siloed baseline (B0) vs Trail, evaluated on the synthetic world (execution plan §6.6).

Unlike ``triage.evaluate_siloed_vs_trail`` (which scores pre-built EvalCase objects),
this module *simulates* both systems from the raw transactions and the simulator's
ground truth, so the comparison is not derived from Trail's own output.

B0 (siloed)  : every institution sees only transactions it is a party to, scores the
               accounts it hosts with the local scorer, and alerts at >= HIGH. Banks
               cannot link their alerts into a ring.
Trail        : the hub sees beacons from *participating* institutions, starts from a
               complaint seed and runs cross-institution graph/ring detection.

Assumptions (also listed in the generated report):
  * one complaint per ring (``complaint_rate`` lowers this), filed ``complaint_delay_min``
    minutes after the seed account first receives funds;
  * a transaction is visible to Trail when its *destination* institution participates
    (the receiving institution emits the derived-funds beacon);
  * exposure ("harm-minutes") for a ring account = minutes from first funds touching it
    until it is flagged, capped at ``horizon_min`` if it is never flagged;
  * unit of analyst work = one account reviewed.

Everything here is synthetic. Results describe the simulator, not production performance.
"""
from __future__ import annotations

import itertools
import random
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from statistics import median
from typing import Any, Sequence

import networkx as nx

from app.detection.graph import detect_ring_from_transactions
from app.detection.lineage import build_transaction_graph
from app.detection.scorer import RiskScorer
from app.models.case import ReceiverClass, RiskLevel, RingRecord
from app.models.transaction import Transaction

HIGH_THRESHOLD = 0.60          # B0 alerts / holds at HIGH or above
IDENTIFIED_FRACTION = 0.80     # a ring counts as "identified" if >= 80% of members are surfaced
DEFAULT_BUDGET_FRACTIONS = (0.5, 1.0, 1.5)   # analyst budget as a multiple of the number of ring accounts

_HIGH = (RiskLevel.HIGH, RiskLevel.CRITICAL)


@dataclass
class EvalConfig:
    budget_fractions: Sequence[float] = DEFAULT_BUDGET_FRACTIONS
    complaint_rate: float = 1.0
    complaint_delay_min: float = 30.0
    hub_latency_min: float = 2.0
    horizon_min: float = 1440.0
    seed: int = 7
    sweep_participation: bool = True


@dataclass
class EvalReport:
    n_rings: int
    n_rings_with_complaint: int
    n_truth_accounts: int
    n_background_accounts: int
    budgets: dict[int, dict[str, float]]
    siloed: dict[str, Any]
    trail: dict[str, Any]
    partial_participation: dict[str, dict[str, float]]
    pattern_detection: dict[str, dict[str, float]]
    assumptions: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "n_rings": self.n_rings,
            "n_rings_with_complaint": self.n_rings_with_complaint,
            "n_truth_accounts": self.n_truth_accounts,
            "n_background_accounts": self.n_background_accounts,
            "budgets": {str(k): v for k, v in self.budgets.items()},
            "siloed": self.siloed,
            "trail": self.trail,
            "partial_participation": self.partial_participation,
            "pattern_detection": self.pattern_detection,
            "assumptions": self.assumptions,
        }

    def to_markdown(self) -> str:
        def f(x: Any, nd: int = 3) -> str:
            if x is None:
                return "never"
            return f"{x:.{nd}f}" if isinstance(x, float) else str(x)

        lines = [
            "# Evaluation: siloed baseline (B0) vs Trail",
            "",
            "_Synthetic data only. Generated by `scripts/run_evaluation.py`; numbers describe the simulator, "
            "not production performance._",
            "",
            f"Rings: {self.n_rings} ({self.n_rings_with_complaint} with a complaint) · "
            f"ring accounts: {self.n_truth_accounts} · other accounts: {self.n_background_accounts}",
            "",
            "## Precision / recall at a fixed analyst budget (accounts reviewed)",
            "",
            "| Budget | B0 precision | B0 recall | Trail precision | Trail recall | B0 innocent | Trail innocent |",
            "|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for k, m in self.budgets.items():
            lines.append(
                f"| {k} | {f(m['precision_siloed'])} | {f(m['recall_siloed'])} | {f(m['precision_trail'])} | "
                f"{f(m['recall_trail'])} | {f(m['innocent_rate_siloed'])} | {f(m['innocent_rate_trail'])} |"
            )
        s, t = self.siloed, self.trail
        lines += [
            "",
            "## Whole-case metrics",
            "",
            "| Metric | B0 (siloed) | Trail |",
            "|---|---:|---:|",
            f"| Rings identified (>= {int(IDENTIFIED_FRACTION * 100)}% of members surfaced) | "
            f"{f(s['ring_identified_rate'])} | {f(t['ring_identified_rate'])} |",
            f"| Median minutes complaint -> ring identified | {f(s['median_minutes_to_ring'], 1)} | "
            f"{f(t['median_minutes_to_ring'], 1)} |",
            f"| Innocent-lien rate (holds on non-ring accounts / all holds) | {f(s['innocent_lien_rate'])} | "
            f"{f(t['innocent_lien_rate'])} |",
            f"| Harm-minutes per ring (summed exposure of its accounts) | {f(s['harm_minutes_per_ring'], 1)} | "
            f"{f(t['harm_minutes_per_ring'], 1)} |",
            f"| Duplicate-alert ratio | {f(s['duplicate_alert_ratio'])} | {f(t['duplicate_alert_ratio'])} |",
            f"| Ring accounts marked likely-legitimate (hold downgraded to verification) | n/a | "
            f"{f(t['ring_accounts_marked_likely_legit'])} |",
            f"| Non-ring accounts surfaced inside cases | n/a | {t['non_ring_accounts_surfaced']} |",
            "",
            "## Trail with partial bank participation",
            "",
            "| Participating institutions | Mean ring-account recall | Mean rings identified |",
            "|---:|---:|---:|",
        ]
        for k, m in self.partial_participation.items():
            lines.append(f"| {k} | {f(m['recall'])} | {f(m['ring_identified_rate'])} |")
        lines += [
            "",
            "## Pattern detection (seed -> detected pattern)",
            "",
            "| Ground-truth pattern | Rings | Pattern matched | Members recovered |",
            "|---|---:|---:|---:|",
        ]
        for p, m in self.pattern_detection.items():
            lines.append(f"| {p} | {int(m['n'])} | {f(m['pattern_match'])} | {f(m['member_recall'])} |")
        lines += ["", "## Assumptions", ""] + [f"- {a}" for a in self.assumptions]
        return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- helpers

def _host_map(txs: Sequence[Transaction]) -> dict[str, str]:
    host: dict[str, str] = {}
    for t in txs:
        host.setdefault(t.source_token, t.source_institution)
        host.setdefault(t.destination_token, t.destination_institution)
    return host


def _first_touch(txs: Sequence[Transaction]) -> dict[str, datetime]:
    first: dict[str, datetime] = {}
    for t in txs:
        for tok in (t.source_token, t.destination_token):
            if tok not in first or t.timestamp < first[tok]:
                first[tok] = t.timestamp
    return first


def _minutes(a: datetime, b: datetime) -> float:
    return (b - a).total_seconds() / 60.0


def _index(txs: Sequence[Transaction]) -> dict[str, list[Transaction]]:
    idx: dict[str, list[Transaction]] = defaultdict(list)
    for t in txs:
        idx[t.source_token].append(t)
        idx[t.destination_token].append(t)
    return idx


def _closure_txs(G: nx.DiGraph, idx: dict[str, list[Transaction]], seed: str) -> list[Transaction]:
    """Transactions touching the seed's reachable set and its direct predecessors.

    Scoring/pattern detection on this reduced list is equivalent to using all
    transactions (features are per-account; fan-in only needs in-edges of reachable nodes).
    """
    reach = nx.descendants(G, seed) | {seed}
    nodes = set(reach)
    for n in reach:
        nodes.update(G.predecessors(n))
    seen: dict[str, Transaction] = {}
    for n in nodes:
        for t in idx.get(n, ()):
            seen[t.transaction_id] = t
    return list(seen.values())


def _trail_rings(
    visible: Sequence[Transaction],
    seeds: dict[int, str],
    scorer: RiskScorer,
) -> dict[int, RingRecord | None]:
    G = build_transaction_graph(visible)
    idx = _index(visible)
    out: dict[int, RingRecord | None] = {}
    for i, seed in seeds.items():
        if seed not in G:
            out[i] = None
            continue
        out[i] = detect_ring_from_transactions(_closure_txs(G, idx, seed), seed, scorer=scorer)
    return out


def _trail_alert_tokens(ring: RingRecord | None) -> set[str]:
    if ring is None:
        return set()
    return {h.token for h in ring.hops if h.receiver_class != ReceiverClass.LEGITIMATE}


def _trail_surfaced_tokens(ring: RingRecord | None) -> set[str]:
    """Every account present in the case (an analyst sees it, including 'likely legitimate' ones)."""
    return {h.token for h in ring.hops} if ring else set()


def _trail_hold_tokens(ring: RingRecord | None) -> set[str]:
    """Accounts that would get a hold proposal (A2): mirrors api/review.py::default_proposals."""
    if ring is None:
        return set()
    return {
        h.token for h in ring.hops
        if h.risk_level in _HIGH and h.receiver_class not in (ReceiverClass.LEGITIMATE, ReceiverClass.RECRUITED)
    }


def _rank_trail_accounts(rings: Sequence[RingRecord | None]) -> list[str]:
    """Order accounts an analyst would review: riskiest case first, riskiest hop first."""
    cases = [r for r in rings if r is not None]
    cases.sort(key=lambda r: -max((h.risk_score for h in r.hops), default=0.0))
    ordered: list[str] = []
    seen: set[str] = set()
    for r in cases:
        for h in sorted(r.hops, key=lambda h: -h.risk_score):
            if h.token not in seen and h.receiver_class != ReceiverClass.LEGITIMATE:
                seen.add(h.token)
                ordered.append(h.token)
    return ordered


def _pr_at_k(ranked: Sequence[str], truth: set[str], k: int) -> tuple[float, float, float]:
    top = list(ranked[:k])
    if not top:
        return 0.0, 0.0, 0.0
    tp = sum(1 for a in top if a in truth)
    innocent = sum(1 for a in top if a not in truth)
    return tp / len(top), tp / len(truth) if truth else 0.0, innocent / len(top)


# ---------------------------------------------------------------- siloed baseline

def siloed_scores(
    txs: Sequence[Transaction],
    scorer: RiskScorer,
    institutions: Sequence[str],
) -> tuple[dict[str, float], dict[str, str]]:
    """Each institution scores the accounts it hosts using only what it can see."""
    host = _host_map(txs)
    scores: dict[str, float] = {}
    for inst in institutions:
        visible = [t for t in txs if t.source_institution == inst or t.destination_institution == inst]
        for tok in (a for a, h in host.items() if h == inst):
            scores[tok] = scorer.score_account(visible, tok).risk_score
    return scores, host


def _siloed_flag_time(
    tok: str, host: str, txs_by_tok: dict[str, list[Transaction]], scorer: RiskScorer
) -> datetime | None:
    """First event time at which the host bank's local score crossed the alert threshold."""
    visible = [t for t in txs_by_tok.get(tok, ()) if t.source_institution == host or t.destination_institution == host]
    for ts in sorted({t.timestamp for t in visible}):
        if scorer.score_account(visible, tok, as_of=ts).risk_score >= HIGH_THRESHOLD:
            return ts
    return None


# ---------------------------------------------------------------- main entry

def run_evaluation(dataset: dict[str, Any], config: EvalConfig | None = None, scorer: RiskScorer | None = None) -> EvalReport:
    """Run B0 vs Trail on a dataset produced by ``simulator.generate_dataset``."""
    cfg = config or EvalConfig()
    scorer = scorer or RiskScorer()
    txs: list[Transaction] = dataset["transactions"]
    ring_meta: list[dict[str, Any]] = dataset["ring_meta"]
    rng = random.Random(cfg.seed)

    institutions = sorted({t.source_institution for t in txs} | {t.destination_institution for t in txs})
    truth = {a for m in ring_meta for a in m["members"]}
    all_accounts = {t.source_token for t in txs} | {t.destination_token for t in txs}
    first_touch = _first_touch(txs)
    idx = _index(txs)

    complained = [i for i in range(len(ring_meta)) if rng.random() < cfg.complaint_rate]
    seeds = {i: ring_meta[i]["seed"] for i in complained}
    complaint_ts = {
        i: first_touch[seeds[i]] + timedelta(minutes=cfg.complaint_delay_min) for i in complained
    }

    # ---- B0 -------------------------------------------------------------
    s_scores, host = siloed_scores(txs, scorer, institutions)
    s_ranked = sorted(s_scores, key=lambda a: (-s_scores[a], a))
    s_alerts = {a for a, v in s_scores.items() if v >= HIGH_THRESHOLD}

    # ---- Trail ----------------------------------------------------------
    rings = _trail_rings(txs, seeds, scorer)
    t_ranked = _rank_trail_accounts(list(rings.values()))
    t_alerts: set[str] = set().union(*(_trail_alert_tokens(r) for r in rings.values())) if rings else set()
    t_holds: set[str] = set().union(*(_trail_hold_tokens(r) for r in rings.values())) if rings else set()

    # ---- precision / recall at budget ----------------------------------
    budgets: dict[int, dict[str, float]] = {}
    for frac in cfg.budget_fractions:
        k = max(1, int(round(frac * len(truth))))
        ps, rs, is_ = _pr_at_k(s_ranked, truth, k)
        pt, rt, it = _pr_at_k(t_ranked, truth, k)
        budgets[k] = {
            "precision_siloed": round(ps, 4), "recall_siloed": round(rs, 4), "innocent_rate_siloed": round(is_, 4),
            "precision_trail": round(pt, 4), "recall_trail": round(rt, 4), "innocent_rate_trail": round(it, 4),
        }

    # ---- identification, time, harm ------------------------------------
    txs_by_tok = idx
    horizon = cfg.horizon_min
    s_identified = t_identified = 0
    s_times: list[float] = []
    t_times: list[float] = []
    s_harm: list[float] = []
    t_harm: list[float] = []
    siloed_flag_cache: dict[str, datetime | None] = {}

    def s_flag(tok: str) -> datetime | None:
        if tok not in siloed_flag_cache:
            siloed_flag_cache[tok] = (
                _siloed_flag_time(tok, host[tok], txs_by_tok, scorer) if tok in s_alerts else None
            )
        return siloed_flag_cache[tok]

    for i in complained:
        members = set(ring_meta[i]["members"])
        need = IDENTIFIED_FRACTION * len(members)

        # B0: a ring is only identified if ONE institution alerts on most of it
        per_inst: dict[str, set[str]] = defaultdict(set)
        for a in members & s_alerts:
            per_inst[host[a]].add(a)
        best = max(per_inst.values(), key=len, default=set())
        if len(best) >= need:
            s_identified += 1
            last = max(s_flag(a) for a in best)  # type: ignore[type-var]
            s_times.append(max(0.0, _minutes(complaint_ts[i], last)))

        # Trail
        surfaced = _trail_surfaced_tokens(rings[i]) & members
        if len(surfaced) >= need:
            t_identified += 1
            last_edge = max(t.timestamp for a in members for t in idx.get(a, ()) if t.source_token in members and t.destination_token in members)
            t_times.append(max(0.0, _minutes(complaint_ts[i], last_edge)) + cfg.hub_latency_min)

        # harm-minutes: exposure of each ring account until it is flagged
        for a in members:
            touch = first_touch[a]
            sf = s_flag(a)
            s_harm.append(horizon if sf is None else min(horizon, max(0.0, _minutes(touch, sf))))
            if a in _trail_alert_tokens(rings[i]):
                flagged = max(complaint_ts[i], touch) + timedelta(minutes=cfg.hub_latency_min)
                t_harm.append(min(horizon, max(0.0, _minutes(touch, flagged))))
            else:
                t_harm.append(horizon)

    n_c = max(1, len(complained))

    def lien_rate(holds: set[str]) -> float:
        return round(len(holds - truth) / len(holds), 4) if holds else 0.0

    # duplicate alerts: B0 opens one case per alerting account (each bank on its own);
    # accounts of the same ring alerted by different banks are duplicates of one real case.
    ring_of: dict[str, int] = {}
    for i, m in enumerate(ring_meta):
        for a in m["members"]:
            ring_of.setdefault(a, i)
    s_cases = len(s_alerts)
    s_distinct = len({ring_of.get(a, f"solo:{a}") for a in s_alerts})
    dup_s = round(1 - s_distinct / s_cases, 4) if s_cases else 0.0
    dup_t = round(1 - len({r.seed_token for r in rings.values() if r}) / max(1, len([r for r in rings.values() if r])), 4)

    legit_marked = {
        h.token for r in rings.values() if r for h in r.hops if h.receiver_class == ReceiverClass.LEGITIMATE
    }
    complained_truth_all = {a for i in complained for a in ring_meta[i]["members"]}
    mule_marked_legit = (
        round(len(legit_marked & complained_truth_all) / len(complained_truth_all), 4) if complained_truth_all else 0.0
    )
    innocent_surfaced = {
        h.token for r in rings.values() if r for h in r.hops
    } - truth
    siloed = {
        "ring_identified_rate": round(s_identified / n_c, 4),
        "median_minutes_to_ring": round(median(s_times), 1) if s_times else None,
        "innocent_lien_rate": lien_rate(s_alerts),
        "harm_minutes_per_ring": round(sum(s_harm) / n_c, 1),
        "duplicate_alert_ratio": dup_s,
        "n_alerts": len(s_alerts),
    }
    trail = {
        "ring_identified_rate": round(t_identified / n_c, 4),
        "median_minutes_to_ring": round(median(t_times), 1) if t_times else None,
        "innocent_lien_rate": lien_rate(t_holds),
        "harm_minutes_per_ring": round(sum(t_harm) / n_c, 1),
        "duplicate_alert_ratio": dup_t,
        "n_alerts": len(t_alerts),
        "ring_accounts_marked_likely_legit": mule_marked_legit,
        "non_ring_accounts_surfaced": len(innocent_surfaced),
    }

    # ---- pattern detection accuracy ------------------------------------
    by_pat: dict[str, list[tuple[bool, float]]] = defaultdict(list)
    for i in complained:
        m = ring_meta[i]
        r = rings[i]
        got = r.pattern if r else None
        # a linear 4-hop multi-institution chain is reported as cross_bank_hop
        ok = got == m["pattern"] or {got, m["pattern"]} <= {"chain", "cross_bank_hop"}
        rec = len({h.token for h in r.hops} & set(m["members"])) / len(m["members"]) if r else 0.0
        by_pat[m["pattern"]].append((ok, rec))
    pattern_detection = {
        p: {"n": float(len(v)), "pattern_match": round(sum(o for o, _ in v) / len(v), 4),
            "member_recall": round(sum(r for _, r in v) / len(v), 4)}
        for p, v in sorted(by_pat.items())
    }

    # ---- partial participation -----------------------------------------
    partial: dict[str, dict[str, float]] = {}
    if cfg.sweep_participation:
        for k in range(1, len(institutions) + 1):
            recs, idents = [], []
            for combo in itertools.combinations(institutions, k):
                part = set(combo)
                visible = [t for t in txs if t.destination_institution in part]
                prings = _trail_rings(visible, seeds, scorer)
                alerted: set[str] = set()
                ident = 0
                for i in complained:
                    members = set(ring_meta[i]["members"])
                    got = _trail_surfaced_tokens(prings[i]) & members
                    alerted |= got
                    ident += len(got) >= IDENTIFIED_FRACTION * len(members)
                complained_truth = {a for i in complained for a in ring_meta[i]["members"]}
                recs.append(len(alerted) / len(complained_truth) if complained_truth else 0.0)
                idents.append(ident / n_c)
            partial[f"{k}/{len(institutions)}"] = {
                "recall": round(sum(recs) / len(recs), 4),
                "ring_identified_rate": round(sum(idents) / len(idents), 4),
            }

    return EvalReport(
        n_rings=len(ring_meta),
        n_rings_with_complaint=len(complained),
        n_truth_accounts=len(truth),
        n_background_accounts=len(all_accounts - truth),
        budgets=budgets,
        siloed=siloed,
        trail=trail,
        partial_participation=partial,
        pattern_detection=pattern_detection,
        assumptions=[
            "B0: each institution sees only transactions it is a party to, scores accounts it hosts, alerts at risk >= 0.60; banks cannot link alerts into a ring.",
            "Trail: complaint seed + cross-institution graph over beacons from participating institutions.",
            f"Complaint filed {cfg.complaint_delay_min:.0f} min after the seed first receives funds; complaint rate {cfg.complaint_rate:.0%}; hub latency {cfg.hub_latency_min:.0f} min.",
            "A transaction is visible to Trail when its destination institution participates (receiver emits the beacon).",
            f"Harm-minutes = minutes from first funds reaching a ring account until it is flagged, capped at {cfg.horizon_min:.0f}.",
            "Innocent-lien rate = share of proposed holds (>= HIGH, not likely-legitimate/recruited for Trail) that land on non-ring accounts.",
            "Duplicate-alert ratio = share of alerts that duplicate another alert of the same ring (B0: one per account per bank; Trail: one case per seed).",
            "Ground truth comes from the simulator; real-world precision/recall will differ.",
        ],
    )
